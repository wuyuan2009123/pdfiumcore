package pdfiumcore.generator;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * Turns the parsed declarations into Java sources using the Foreign Function &amp; Memory API.
 */
final class JavaEmitter {

    private static final Set<String> JAVA_KEYWORDS = Set.of(
            "abstract", "assert", "boolean", "break", "byte", "case", "catch", "char", "class",
            "const", "continue", "default", "do", "double", "else", "enum", "extends", "final",
            "finally", "float", "for", "goto", "if", "implements", "import", "instanceof", "int",
            "interface", "long", "native", "new", "package", "private", "protected", "public",
            "return", "short", "static", "strictfp", "super", "switch", "synchronized", "this",
            "throw", "throws", "transient", "try", "void", "volatile", "while", "record", "sealed",
            "permits", "var", "yield", "true", "false", "null");

    private final HeaderParser parser;
    private final TypeSystem types;
    private final Path outputDir;
    private final String packageName;
    private final String sourceDescription;
    private final List<String> warnings = new ArrayList<>();
    private final List<String> generated = new ArrayList<>();
    private final Map<String, String> structClassNames = new HashMap<>();
    private final Map<String, Integer> structSizes = new HashMap<>();
    private final Map<String, Integer> structAligns = new HashMap<>();

    JavaEmitter(HeaderParser parser, TypeSystem types, Path outputDir, String packageName,
                String sourceDescription) {
        this.parser = parser;
        this.types = types;
        this.outputDir = outputDir;
        this.packageName = packageName;
        this.sourceDescription = sourceDescription;
    }

    List<String> warnings() {
        return warnings;
    }

    void emitAll() throws IOException {
        Path pkgDir = outputDir.resolve(packageName.replace('.', '/'));
        Files.createDirectories(pkgDir);

        // Remove the sources produced by the previous run so that renamed or dropped
        // declarations do not linger in the output directory.
        Path manifest = pkgDir.resolve(".generated-files");
        if (Files.isRegularFile(manifest)) {
            for (String line : Files.readAllLines(manifest, StandardCharsets.UTF_8)) {
                if (!line.isBlank() && !line.startsWith("#")) {
                    Files.deleteIfExists(pkgDir.resolve(line.trim()));
                }
            }
        }

        for (Declarations.EnumDef def : parser.enums().values()) {
            write(pkgDir, def.name, emitEnum(def));
        }
        // Windows file systems are case insensitive, so a struct such as FPDF_SYSFONTINFO
        // cannot live next to the fpdf_sysfontinfo function class; disambiguate those.
        Set<String> headerNames = new HashSet<>();
        for (Declarations.FuncDef fn : parser.functions()) {
            headerNames.add(fn.header.toLowerCase(java.util.Locale.ROOT));
        }
        for (String struct : parser.structs().keySet()) {
            structClassNames.put(struct, headerNames.contains(struct.toLowerCase(java.util.Locale.ROOT))
                    ? struct + "_" : struct);
        }
        // Sizes have to be known before structs and by-value struct parameters are emitted.
        for (Declarations.StructDef def : parser.structs().values()) {
            sizeOf(def.name);
        }
        for (Declarations.StructDef def : parser.structs().values()) {
            write(pkgDir, className(def.name), emitStruct(def));
        }
        for (Declarations.CallbackDef def : parser.callbacks().values()) {
            write(pkgDir, def.name, emitCallback(def));
        }

        Map<String, List<Declarations.FuncDef>> byHeader = new LinkedHashMap<>();
        for (Declarations.FuncDef fn : parser.functions()) {
            byHeader.computeIfAbsent(fn.header, k -> new ArrayList<>()).add(fn);
        }
        for (Map.Entry<String, List<Declarations.FuncDef>> entry : byHeader.entrySet()) {
            write(pkgDir, entry.getKey(), emitFunctions(entry.getKey(), entry.getValue()));
        }

        Files.writeString(manifest,
                "# Files generated by pdfiumcore-bindings-generator; do not edit.\n"
                        + String.join("\n", generated) + "\n",
                StandardCharsets.UTF_8);
    }

    private void write(Path dir, String name, String content) throws IOException {
        String fileName = name + ".java";
        Files.writeString(dir.resolve(fileName), content, StandardCharsets.UTF_8);
        generated.add(fileName);
    }

    // ------------------------------------------------------------------ enums

    private String emitEnum(Declarations.EnumDef def) {
        StringBuilder sb = new StringBuilder();
        sb.append(fileHeader());
        sb.append("package ").append(packageName).append(";\n\n");
        appendDoc(sb, def.doc, "");
        sb.append("public enum ").append(def.name).append(" {\n");
        Map<String, Long> known = new LinkedHashMap<>();
        List<Map.Entry<String, String>> entries = new ArrayList<>(def.constants.entrySet());
        for (int i = 0; i < entries.size(); i++) {
            Map.Entry<String, String> e = entries.get(i);
            long value = evaluate(e.getValue(), known, def.name);
            known.put(e.getKey(), value);
            sb.append("    ").append(e.getKey()).append("(").append(value).append(")");
            sb.append(i == entries.size() - 1 ? ";\n" : ",\n");
        }
        sb.append("""
                
                    private final int value;
                
                """);
        sb.append("    ").append(def.name).append("(int value) {\n        this.value = value;\n    }\n\n");
        sb.append("    public int value() {\n        return value;\n    }\n\n");
        sb.append("    public static ").append(def.name).append(" of(int value) {\n");
        sb.append("        for (").append(def.name).append(" candidate : values()) {\n");
        sb.append("            if (candidate.value == value) {\n                return candidate;\n            }\n");
        sb.append("        }\n        throw new IllegalArgumentException(\"Unknown ").append(def.name)
                .append(" value: \" + value);\n    }\n}\n");
        return sb.toString();
    }

    private long evaluate(String expr, Map<String, Long> known, String owner) {
        if (expr == null || expr.isBlank()) {
            return known.size();
        }
        String e = expr.trim();
        while (e.startsWith("(") && e.endsWith(")") && balanced(e.substring(1, e.length() - 1))) {
            e = e.substring(1, e.length() - 1).trim();
        }
        Long reference = known.get(e);
        if (reference != null) {
            return reference;
        }
        int shift = e.indexOf("<<");
        if (shift > 0) {
            try {
                long left = Long.parseLong(e.substring(0, shift).trim());
                long right = Long.parseLong(e.substring(shift + 2).trim());
                return left << right;
            } catch (NumberFormatException ignored) {
                // fall through
            }
        }
        try {
            if (e.startsWith("0x") || e.startsWith("0X")) {
                return Long.parseLong(e.substring(2), 16);
            }
            return Long.parseLong(e);
        } catch (NumberFormatException ex) {
            warnings.add("Could not evaluate enum constant " + owner + " = " + expr);
            return 0;
        }
    }

    private static boolean balanced(String s) {
        int depth = 0;
        for (int i = 0; i < s.length(); i++) {
            if (s.charAt(i) == '(') {
                depth++;
            } else if (s.charAt(i) == ')') {
                depth--;
                if (depth < 0) {
                    return false;
                }
            }
        }
        return depth == 0;
    }

    // ------------------------------------------------------------------ structs

    private int sizeOf(String structName) {
        Integer cached = structSizes.get(structName);
        if (cached != null) {
            return cached;
        }
        Declarations.StructDef def = parser.structs().get(structName);
        if (def == null) {
            return 8;
        }
        structSizes.put(structName, 0);
        int offset = 0;
        int align = 1;
        for (Declarations.Field field : def.fields) {
            int fieldSize = fieldSize(field);
            int fieldAlign = fieldAlign(field);
            offset = alignUp(offset, fieldAlign);
            offset += fieldSize;
            align = Math.max(align, fieldAlign);
        }
        int total = alignUp(offset, align);
        structSizes.put(structName, total);
        structAligns.put(structName, align);
        return total;
    }

    private int fieldSize(Declarations.Field field) {
        if (field.isFunctionPointer()) {
            return 8;
        }
        return sizeOf(field.type);
    }

    private int fieldAlign(Declarations.Field field) {
        if (field.isFunctionPointer()) {
            return 8;
        }
        return alignOf(field.type);
    }

    private int sizeOf(CType type) {
        switch (type.kind) {
            case PRIMITIVE:
                return types.primitiveFor(type.name).size;
            case ENUM:
                return 4;
            case POINTER:
            case CALLBACK:
            case UNKNOWN:
                return 8;
            case STRUCT:
                return sizeOf(type.name);
            default:
                return 0;
        }
    }

    private int alignOf(CType type) {
        switch (type.kind) {
            case PRIMITIVE:
                return types.primitiveFor(type.name).align;
            case ENUM:
                return 4;
            case POINTER:
            case CALLBACK:
            case UNKNOWN:
                return 8;
            case STRUCT: {
                sizeOf(type.name);
                return structAligns.getOrDefault(type.name, 8);
            }
            default:
                return 1;
        }
    }

    private static int alignUp(int value, int align) {
        return (value + align - 1) / align * align;
    }

    private String emitStruct(Declarations.StructDef def) {
        String cname = className(def.name);
        StringBuilder sb = new StringBuilder();
        sb.append(fileHeader());
        sb.append("package ").append(packageName).append(";\n\n");
        sb.append("import java.lang.foreign.Arena;\n");
        sb.append("import java.lang.foreign.MemoryLayout;\n");
        sb.append("import java.lang.foreign.MemorySegment;\n");
        sb.append("import static java.lang.foreign.ValueLayout.*;\n\n");
        appendDoc(sb, def.doc, "");
        sb.append("public final class ").append(cname).append(" implements AutoCloseable {\n\n");

        // Layout with explicit padding so that the C ABI offsets are preserved.
        sb.append("    public static final MemoryLayout LAYOUT = MemoryLayout.structLayout(\n");
        List<String> layouts = new ArrayList<>();
        int offset = 0;
        for (Declarations.Field field : def.fields) {
            int align = fieldAlign(field);
            int size = fieldSize(field);
            int aligned = alignUp(offset, align);
            if (aligned > offset) {
                layouts.add("MemoryLayout.paddingLayout(" + (aligned - offset) + ")");
            }
            String layout = field.isFunctionPointer() ? "ADDRESS" : layoutOf(field.type);
            layouts.add(layout + ".withName(\"" + field.name + "\")");
            offset = aligned + size;
        }
        int total = alignUp(offset, Math.max(1, structAligns.getOrDefault(def.name, 1)));
        if (total > offset) {
            layouts.add("MemoryLayout.paddingLayout(" + (total - offset) + ")");
        }
        for (int i = 0; i < layouts.size(); i++) {
            sb.append("        ").append(layouts.get(i));
            sb.append(i == layouts.size() - 1 ? "\n" : ",\n");
        }
        sb.append("    );\n\n");

        sb.append("    private final Arena arena;\n    private final MemorySegment segment;\n\n");
        sb.append("    public ").append(cname).append("() {\n");
        sb.append("        this.arena = Arena.ofConfined();\n");
        sb.append("        this.segment = arena.allocate(LAYOUT);\n    }\n\n");
        sb.append("    /** Wraps an existing native structure without taking ownership of it. */\n");
        sb.append("    public ").append(cname).append("(MemorySegment segment) {\n");
        sb.append("        this.arena = null;\n");
        sb.append("        this.segment = segment.reinterpret(LAYOUT.byteSize());\n    }\n\n");
        sb.append("    public MemorySegment segment() {\n        return segment;\n    }\n\n");
        sb.append("    public static ").append(cname).append(" of(MemorySegment segment) {\n");
        sb.append("        return new ").append(cname).append("(segment);\n    }\n\n");

        offset = 0;
        for (Declarations.Field field : def.fields) {
            int align = fieldAlign(field);
            int size = fieldSize(field);
            offset = alignUp(offset, align);
            String name = safeName(field.name);
            long off = offset;
            if (field.isFunctionPointer()) {
                sb.append("    public MemorySegment ").append(name).append("() {\n");
                sb.append("        return segment.get(ADDRESS, ").append(off).append("L);\n    }\n\n");
                sb.append("    public ").append(cname).append(" ").append(name)
                        .append("(MemorySegment value) {\n");
                sb.append("        segment.set(ADDRESS, ").append(off).append("L, value);\n");
                sb.append("        return this;\n    }\n\n");
            } else {
                // Struct fields always expose raw pointers: a char* field cannot be turned into a
                // Java String without knowing who owns the memory.
                String javaType = javaTypeOf(field.type, true);
                String layout = layoutOf(field.type);
                sb.append("    public ").append(javaType).append(" ").append(name).append("() {\n");
                sb.append("        return segment.get(").append(layout).append(", ").append(off)
                        .append("L);\n    }\n\n");
                sb.append("    public ").append(cname).append(" ").append(name).append("(")
                        .append(javaType).append(" value) {\n");
                sb.append("        segment.set(").append(layout).append(", ").append(off)
                        .append("L, value);\n");
                sb.append("        return this;\n    }\n\n");
            }
            offset += size;
        }

        sb.append("    @Override\n    public void close() {\n");
        sb.append("        if (arena != null) {\n            arena.close();\n        }\n    }\n");
        sb.append("}\n");
        return sb.toString();
    }

    private String className(String structName) {
        return structClassNames.getOrDefault(structName, structName);
    }

    // ------------------------------------------------------------------ callbacks

    private String emitCallback(Declarations.CallbackDef def) {
        String returnType = javaTypeOf(def.returnType, true);
        boolean structReturn = def.returnType.kind == CType.Kind.STRUCT;
        StringBuilder sb = new StringBuilder();
        sb.append(fileHeader());
        sb.append("package ").append(packageName).append(";\n\n");
        sb.append("import java.lang.foreign.Arena;\n");
        sb.append("import java.lang.foreign.FunctionDescriptor;\n");
        sb.append("import java.lang.foreign.MemorySegment;\n");
        sb.append("import java.lang.invoke.MethodHandle;\n");
        sb.append("import java.lang.invoke.MethodHandles;\n");
        sb.append("import java.lang.invoke.MethodType;\n");
        sb.append("import static java.lang.foreign.ValueLayout.*;\n\n");
        appendDoc(sb, def.doc, "");
        sb.append("@FunctionalInterface\n");
        sb.append("public interface ").append(def.name).append(" {\n\n");
        sb.append("    ").append(returnType).append(" invoke(");
        sb.append(paramDecls(def.params, false)).append(");\n\n");

        if (structReturn) {
            sb.append("    // A struct return value cannot be produced by a Foreign Function & Memory\n");
            sb.append("    // upcall; pass a native function pointer for this callback instead.\n");
        } else {
            sb.append("    /** Creates an upcall stub which can be stored in a native callback slot. */\n");
            sb.append("    static MemorySegment stub(Arena arena, ").append(def.name).append(" callback) {\n");
            sb.append("        try {\n");
            sb.append("            MethodHandle handle = MethodHandles.lookup()\n");
            sb.append("                    .findVirtual(").append(def.name).append(".class, \"invoke\",\n");
            sb.append("                            MethodType.methodType(").append(classOf(def.returnType));
            sb.append(".class");
            for (Declarations.Param p : def.params) {
                sb.append(", ").append(classOf(p.type)).append(".class");
            }
            sb.append("))\n");
            sb.append("                    .bindTo(callback);\n");
            sb.append("            return PdfiumLibrary.upcall(handle, ");
            sb.append(descriptor(def.returnType, def.params)).append(", arena);\n");
            sb.append("        } catch (ReflectiveOperationException e) {\n");
            sb.append("            throw new IllegalStateException(e);\n        }\n    }\n");
        }
        sb.append("}\n");
        return sb.toString();
    }

    // ------------------------------------------------------------------ functions

    private String emitFunctions(String header, List<Declarations.FuncDef> functions) {
        StringBuilder sb = new StringBuilder();
        sb.append(fileHeader());
        sb.append("package ").append(packageName).append(";\n\n");
        sb.append("import java.lang.foreign.Arena;\n");
        sb.append("import java.lang.foreign.FunctionDescriptor;\n");
        sb.append("import java.lang.foreign.MemorySegment;\n");
        sb.append("import java.lang.invoke.MethodHandle;\n");
        sb.append("import static java.lang.foreign.ValueLayout.*;\n\n");
        sb.append("/**\n * Bindings for <b>").append(header).append(".h</b>.\n");
        sb.append(" * <p>Generated from the PDFium public header files; do not edit.\n */\n");
        sb.append("public final class ").append(header).append(" {\n\n");
        sb.append("    private ").append(header).append("() {\n    }\n\n");

        for (Declarations.FuncDef fn : functions) {
            sb.append("    private static final class H_").append(fn.name).append(" {\n");
            sb.append("        static final MethodHandle MH = PdfiumLibrary.downcall(\"")
                    .append(fn.name).append("\",\n                ")
                    .append(descriptor(fn.returnType, fn.params)).append(");\n    }\n\n");
            appendDoc(sb, fn.doc, "    ");
            sb.append("    public static ").append(javaTypeOf(fn.returnType, true)).append(" ")
                    .append(fn.name).append("(").append(paramDecls(fn.params, false)).append(") {\n");

            boolean hasString = fn.params.stream().anyMatch(p -> isStringParam(p.type));
            String indent = "            ";
            if (hasString) {
                sb.append("        try (Arena arena = Arena.ofConfined()) {\n");
            } else {
                sb.append("        try {\n");
            }
            List<String> args = new ArrayList<>();
            for (Declarations.Param p : fn.params) {
                String name = safeName(p.name);
                args.add(isStringParam(p.type) ? "PdfiumRuntime.utf8(arena, " + name + ")" : name);
            }
            String call = "H_" + fn.name + ".MH.invokeExact(" + String.join(", ", args) + ")";
            if (fn.returnType.isVoid()) {
                sb.append(indent).append(call).append(";\n");
            } else {
                sb.append(indent).append("return (").append(javaTypeOf(fn.returnType, true)).append(") ")
                        .append(call).append(";\n");
            }
            sb.append("        } catch (Throwable t) {\n");
            sb.append("            throw PdfiumRuntime.rethrow(t);\n        }\n");
            sb.append("    }\n\n");
        }
        sb.append("}\n");
        return sb.toString();
    }

    // ------------------------------------------------------------------ type mapping

    private boolean isStringParam(CType type) {
        return type.kind == CType.Kind.POINTER && type.isConst && type.isCharPointer();
    }

    private String javaTypeOf(CType type, boolean returnPosition) {
        switch (type.kind) {
            case VOID:
                return "void";
            case PRIMITIVE:
                return types.primitiveFor(type.name).javaType;
            case ENUM:
                return "int";
            case POINTER:
                if (!returnPosition && isStringParam(type)) {
                    return "String";
                }
                return "MemorySegment";
            case STRUCT:
            case CALLBACK:
            case UNKNOWN:
            default:
                return "MemorySegment";
        }
    }

    private String layoutOf(CType type) {
        switch (type.kind) {
            case PRIMITIVE:
                return types.primitiveFor(type.name).layout;
            case ENUM:
                return "JAVA_INT";
            case STRUCT:
                return className(type.name) + ".LAYOUT";
            default:
                return "ADDRESS";
        }
    }

    private String classOf(CType type) {
        switch (type.kind) {
            case VOID:
                return "void";
            case PRIMITIVE:
                return types.primitiveFor(type.name).javaType;
            case ENUM:
                return "int";
            default:
                return "MemorySegment";
        }
    }

    private String descriptor(CType returnType, List<Declarations.Param> params) {
        List<String> layouts = new ArrayList<>();
        for (Declarations.Param p : params) {
            layouts.add(layoutOf(p.type));
        }
        if (returnType.isVoid()) {
            return "FunctionDescriptor.ofVoid(" + String.join(", ", layouts) + ")";
        }
        String joined = String.join(", ", layouts);
        return "FunctionDescriptor.of(" + layoutOf(returnType)
                + (joined.isEmpty() ? "" : ", " + joined) + ")";
    }

    private String paramDecls(List<Declarations.Param> params, boolean annotate) {
        List<String> out = new ArrayList<>();
        for (Declarations.Param p : params) {
            out.add(javaTypeOf(p.type, false) + " " + safeName(p.name));
        }
        return String.join(", ", out);
    }

    private static String safeName(String name) {
        if (name == null || name.isBlank()) {
            return "arg";
        }
        String n = name.replace("$", "_");
        if (JAVA_KEYWORDS.contains(n)) {
            n = n + "_";
        }
        if (!Character.isJavaIdentifierStart(n.charAt(0))) {
            n = "_" + n;
        }
        return n;
    }

    // ------------------------------------------------------------------ comments

    private String fileHeader() {
        return "// " + sourceDescription + "\n"
                + "// ----------------------------------------------------------------------------\n"
                + "// <auto-generated>\n"
                + "// This is autogenerated code by PDFiumCoreBindingsGenerator.\n"
                + "// Do not edit this file or all your changes will be lost after re-generation.\n"
                + "// </auto-generated>\n"
                + "// ----------------------------------------------------------------------------\n";
    }

    private void appendDoc(StringBuilder sb, String doc, String indent) {
        if (doc == null || doc.isBlank()) {
            return;
        }
        sb.append(indent).append("/**\n").append(indent).append(" * <pre>\n");
        for (String line : doc.split("\n")) {
            sb.append(indent).append(" * ").append(escape(line.stripTrailing())).append('\n');
        }
        sb.append(indent).append(" * </pre>\n").append(indent).append(" */\n");
    }

    private static String escape(String s) {
        return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("*/", "*&#47;");
    }
}
